package com.payment.nadi.infrastructure.security.biometric;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.Signature;
import java.util.Base64;

import static org.junit.jupiter.api.Assertions.*;

class BiometricServiceTest {

    private BiometricService biometricService;

    @BeforeEach
    void setUp() {
        biometricService = new BiometricService();
    }

    @Test
    @DisplayName("Should generate 64-character hex cryptographic challenge nonce")
    void shouldGenerateChallenge() {
        String challenge = biometricService.generateChallenge("+251911223344");
        assertNotNull(challenge);
        assertEquals(64, challenge.length(), "32 bytes hex encoded should be 64 characters");
        assertTrue(challenge.matches("^[0-9a-f]{64}$"));
    }

    @Test
    @DisplayName("Should verify valid ECDSA signature generated by client device")
    void shouldVerifyValidEcdsaSignature() throws Exception {
        // 1. Simulate mobile hardware / Secure Enclave generating an EC key pair
        KeyPairGenerator kpg = KeyPairGenerator.getInstance("EC");
        kpg.initialize(256);
        KeyPair keyPair = kpg.generateKeyPair();

        String publicKeyBase64 = Base64.getEncoder().encodeToString(keyPair.getPublic().getEncoded());

        // 2. Server generates challenge
        String challenge = biometricService.generateChallenge("+251911223344");

        // 3. Client device biometric sensor signs challenge with private key
        Signature signer = Signature.getInstance("SHA256withECDSA");
        signer.initSign(keyPair.getPrivate());
        signer.update(challenge.getBytes(StandardCharsets.UTF_8));
        byte[] sigBytes = signer.sign();
        String signatureBase64 = Base64.getEncoder().encodeToString(sigBytes);

        // 4. Server verifies signature
        boolean valid = biometricService.verifySignature(publicKeyBase64, challenge, signatureBase64);
        assertTrue(valid, "Valid ECDSA signature must verify successfully");
    }

    @Test
    @DisplayName("Should reject tampered challenge or forged signature")
    void shouldRejectForgedSignature() throws Exception {
        KeyPairGenerator kpg = KeyPairGenerator.getInstance("EC");
        kpg.initialize(256);
        KeyPair keyPair = kpg.generateKeyPair();

        String publicKeyBase64 = Base64.getEncoder().encodeToString(keyPair.getPublic().getEncoded());
        String challenge = biometricService.generateChallenge("+251911223344");

        Signature signer = Signature.getInstance("SHA256withECDSA");
        signer.initSign(keyPair.getPrivate());
        signer.update("TAMPERED_CHALLENGE".getBytes(StandardCharsets.UTF_8));
        String forgedSig = Base64.getEncoder().encodeToString(signer.sign());

        boolean valid = biometricService.verifySignature(publicKeyBase64, challenge, forgedSig);
        assertFalse(valid, "Signature over tampered challenge must be rejected");
    }

    @Test
    @DisplayName("Should enforce anti-replay by preventing challenge re-use")
    void shouldEnforceAntiReplayOnChallenge() {
        String identifier = "+251911223344";
        String challenge = biometricService.generateChallenge(identifier);

        // First consumption succeeds
        boolean first = biometricService.consumeChallenge(challenge, identifier);
        assertTrue(first, "First consumption should succeed");

        // Second consumption fails (anti-replay)
        boolean second = biometricService.consumeChallenge(challenge, identifier);
        assertFalse(second, "Replay attempt must be rejected");
    }
}
